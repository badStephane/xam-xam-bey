"""Génère la migration « bibliothèque et administration » (une seule fois).

- Tables admins, documents, cards ; fonction is_admin() ; règles d'accès (RLS) ; bucket de stockage « documents ».
- Reprise des 170 documents du catalogue (data/catalog.site.json) avec leurs identifiants actuels.
- Transfert des cartes de revision_content (cards-N) vers la table cards, liées à leur document source.

Usage : python3 scripts/library_sql.py  →  supabase/migrations/<horodatage>_library.sql

La base fait foi pour les documents et les cartes (ADR-1, docs/squad/decisions.md) : la reprise des documents et
le transfert des cartes utilisent `on conflict (id) do nothing`, jamais `do update`, pour ne pas écraser ce que
l'admin a modifié. Seules la configuration du bucket (taille, types MIME) et une correction ponctuelle de source
(cartes encore sans document) sont réécrites. Ne pas relancer ce script :
sa migration est déjà appliquée ; une évolution passe par une nouvelle migration écrite à la main.
"""
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "data" / "catalog.site.json"
OUT_DIR = ROOT / "supabase" / "migrations"
MAX_FILE_BYTES = 50 * 1024 * 1024

SCHEMA = f"""
-- Administrateurs : une liste d'e-mails. Ajout : insert into public.admins (email) values ('prenom@exemple.sn');
create table if not exists public.admins (
  email text primary key check (email = lower(email) and email like '%@%'),
  added_at timestamptz not null default now()
);
alter table public.admins enable row level security;
drop policy if exists "Lecture de sa propre ligne d'admin" on public.admins;
create policy "Lecture de sa propre ligne d'admin" on public.admins for select to authenticated
  using (email = lower(coalesce((select auth.jwt() ->> 'email'), '')));
revoke all on public.admins from anon;
revoke insert, update, delete on public.admins from authenticated;

create or replace function public.is_admin() returns boolean
  language sql stable security definer set search_path = ''
as $$
  -- Lié au compte (auth.uid) et à une adresse confirmée, pas seulement à l'e-mail présent dans le jeton.
  select exists (
    select 1 from public.admins a
    join auth.users u on lower(u.email) = a.email
    where u.id = auth.uid() and u.email_confirmed_at is not null
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Documents de la bibliothèque (lecture publique, écriture réservée aux admins).
create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  zone smallint not null check (zone between 1 and 12),
  title text not null check (length(trim(title)) between 1 and 200),
  folder text not null default '' check (length(folder) <= 200),
  file_name text not null check (length(file_name) between 1 and 255),
  storage_path text not null unique check (storage_path ~ '^[A-Za-z0-9._-]+\\.pdf$'),
  size bigint not null check (size > 0 and size <= {MAX_FILE_BYTES}),
  pages integer check (pages > 0),
  essential boolean not null default false,
  scan boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users (id) on delete set null
);
create index if not exists documents_zone_idx on public.documents (zone, id);
alter table public.documents enable row level security;
drop policy if exists "Lecture publique des documents" on public.documents;
create policy "Lecture publique des documents" on public.documents for select to anon, authenticated using (true);
drop policy if exists "Ajout de documents par les admins" on public.documents;
create policy "Ajout de documents par les admins" on public.documents for insert to authenticated with check ((select public.is_admin()));
drop policy if exists "Modification de documents par les admins" on public.documents;
create policy "Modification de documents par les admins" on public.documents for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Suppression de documents par les admins" on public.documents;
create policy "Suppression de documents par les admins" on public.documents for delete to authenticated using ((select public.is_admin()));
revoke insert, update, delete on public.documents from anon;
-- Lecture publique limitée aux colonnes utiles (created_by reste privé).
revoke select on public.documents from anon, authenticated;
grant select (id, zone, title, folder, file_name, storage_path, size, pages, essential, scan, created_at, updated_at) on public.documents to anon, authenticated;

-- Fichiers : bucket public en lecture (lecteur intégré), PDF de {MAX_FILE_BYTES // 1024 // 1024} Mo au plus, écriture réservée aux admins.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('documents', 'documents', true, {MAX_FILE_BYTES}, array['application/pdf'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "Envoi de documents par les admins" on storage.objects;
create policy "Envoi de documents par les admins" on storage.objects for insert to authenticated
  with check (bucket_id = 'documents' and name ~ '^[A-Za-z0-9._-]+\\.pdf$' and (select public.is_admin()));
drop policy if exists "Remplacement de documents par les admins" on storage.objects;
create policy "Remplacement de documents par les admins" on storage.objects for update to authenticated
  using (bucket_id = 'documents' and (select public.is_admin()))
  with check (bucket_id = 'documents' and name ~ '^[A-Za-z0-9._-]+\\.pdf$' and (select public.is_admin()));
drop policy if exists "Suppression de fichiers par les admins" on storage.objects;
create policy "Suppression de fichiers par les admins" on storage.objects for delete to authenticated
  using (bucket_id = 'documents' and (select public.is_admin()));

-- Questions de révision : une ligne par carte, rattachée à une zone et à son document source.
create table if not exists public.cards (
  id text primary key check (id ~ '^[a-z0-9-]{{3,40}}$'),
  zone smallint not null check (zone between 1 and 12),
  document_id bigint references public.documents (id) on delete set null,
  position integer not null default 0,
  q text not null check (length(trim(q)) > 0),
  a text not null check (length(trim(a)) > 0),
  src text not null default '',
  note text not null default '',
  qcm jsonb check (qcm is null or (jsonb_typeof(qcm -> 'ok') = 'string' and jsonb_typeof(qcm -> 'no') = 'array')),
  status text not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users (id) on delete set null
);
create index if not exists cards_zone_idx on public.cards (zone, position);
create index if not exists cards_document_idx on public.cards (document_id);
alter table public.cards enable row level security;
drop policy if exists "Lecture des cartes publiées" on public.cards;
create policy "Lecture des cartes publiées" on public.cards for select to authenticated
  using (status = 'published' or (select public.is_admin()));
drop policy if exists "Ajout de cartes par les admins" on public.cards;
create policy "Ajout de cartes par les admins" on public.cards for insert to authenticated with check ((select public.is_admin()));
drop policy if exists "Modification de cartes par les admins" on public.cards;
create policy "Modification de cartes par les admins" on public.cards for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Suppression de cartes par les admins" on public.cards;
create policy "Suppression de cartes par les admins" on public.cards for delete to authenticated using ((select public.is_admin()));
revoke all on public.cards from anon;

-- Horodatage des modifications.
create or replace function public.touch_updated_at() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists documents_touch on public.documents;
create trigger documents_touch before update on public.documents for each row execute function public.touch_updated_at();
drop trigger if exists cards_touch on public.cards;
create trigger cards_touch before update on public.cards for each row execute function public.touch_updated_at();
"""

CARDS_MOVE = """
-- Transfert des cartes publiées (revision_content « cards-N ») vers la table cards, liées au document cité en premier dans leur source.
insert into public.cards (id, zone, position, q, a, src, note, qcm, status, document_id)
select c ->> 'id', substring(rc.id from 7)::smallint, t.ord::integer, c ->> 'q', c ->> 'a',
       coalesce(c ->> 'src', ''), coalesce(c ->> 'note', ''), c -> 'qcm', 'published',
       (select d.id from public.documents d
         where left(coalesce(c ->> 'src', ''), length(d.file_name)) = d.file_name
         order by length(d.file_name) desc, d.id limit 1)
from public.revision_content rc
cross join lateral jsonb_array_elements(rc.data -> 'cards') with ordinality as t(c, ord)
where rc.id like 'cards-%'
on conflict (id) do nothing;
-- Sources citées avec une orthographe différente du nom de fichier réel.
update public.cards c set document_id = d.id, src = replace(c.src, 'la devise, l''esprit et les éléments fondamentaux du scoutismes.docx', d.file_name)
from public.documents d
where c.document_id is null and d.file_name = 'la devise, l_esprit et les élements fondamentaux du scoutismes.docx' and c.src like 'la devise, l''esprit et les éléments fondamentaux du scoutismes.docx' || '%';
delete from public.revision_content where id like 'cards-%';
"""


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    items = json.loads(CATALOG.read_text(encoding="utf-8"))
    rows = []
    for i, it in enumerate(items, 1):
        if it.get("d"):
            continue  # doublon : même fichier qu'une autre entrée
        pages = str(it["g"]) if it.get("g") else "null"
        rows.append(f"  ({i}, {it['th']}, {q(it['t'])}, {q(it['p'])}, {q(it['n'])}, {q(it['f'])}, {it['s']}, {pages}, {str(bool(it.get('es'))).lower()}, {str(bool(it.get('x'))).lower()})")
    docs = ("\n-- Reprise du catalogue actuel (identifiants conservés pour l'historique « consultées » des visiteurs).\n"
            "insert into public.documents (id, zone, title, folder, file_name, storage_path, size, pages, essential, scan) values\n"
            + ",\n".join(rows)
            + "\non conflict (id) do nothing;\n"
            "select setval(pg_get_serial_sequence('public.documents', 'id'), (select max(id) from public.documents));\n")
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S")
    out = OUT_DIR / f"{stamp}_library.sql"
    out.write_text("-- Bibliothèque dans Supabase et espace d'administration (généré par scripts/library_sql.py).\n"
                   + SCHEMA + docs + CARDS_MOVE, encoding="utf-8")
    print(f"{out.relative_to(ROOT)} : {len(rows)} documents, {out.stat().st_size // 1024} Ko")


if __name__ == "__main__":
    main()
